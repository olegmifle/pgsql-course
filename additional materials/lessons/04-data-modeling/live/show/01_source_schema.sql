CREATE TABLE live04_projection.companies (
    id bigint PRIMARY KEY,
    name text NOT NULL
);

CREATE TABLE live04_projection.operations (
    id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    company_id bigint NOT NULL REFERENCES live04_projection.companies(id),
    business_date date NOT NULL,
    request_key text NOT NULL,
    amount_cents bigint NOT NULL,
    UNIQUE (company_id, request_key)
);

CREATE FUNCTION live04_projection.keep_operation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Операция неизменяема; исправление — новая операция';
END $$;

CREATE TRIGGER operation_is_immutable
BEFORE UPDATE OR DELETE ON live04_projection.operations
FOR EACH ROW EXECUTE FUNCTION live04_projection.keep_operation();
