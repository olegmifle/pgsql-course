\set ON_ERROR_STOP on
BEGIN;
CREATE SCHEMA hw06;
SET LOCAL search_path=hw06,public;
CREATE TABLE organizations (
  id bigint PRIMARY KEY,
  name text NOT NULL,
  reservation_limit integer NOT NULL CHECK (reservation_limit>=0)
);
CREATE TABLE inventory (
  sku bigint PRIMARY KEY,
  title text NOT NULL,
  initial_qty integer NOT NULL CHECK (initial_qty>=0),
  available integer NOT NULL CHECK (available>=0 AND available<=initial_qty)
);
CREATE TABLE reservations (
  id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations,
  sku bigint NOT NULL REFERENCES inventory,
  qty integer NOT NULL CHECK (qty>0),
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','cancelled')),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX ON reservations (organization_id) WHERE status='active';
CREATE TABLE wallets (
  id bigint PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organizations,
  initial_balance numeric(12,2) NOT NULL CHECK (initial_balance>=0),
  balance numeric(12,2) NOT NULL CHECK (balance>=0),
  UNIQUE (organization_id,id)
);
CREATE TABLE debit_operations (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL,
  request_key text NOT NULL CHECK (length(request_key) BETWEEN 1 AND 100),
  wallet_id bigint NOT NULL,
  amount numeric(12,2) NOT NULL CHECK (amount>0),
  outcome text NOT NULL CHECK (outcome IN ('pending','approved','declined')),
  balance_after numeric(12,2),
  job_id bigint,
  UNIQUE (organization_id,request_key),
  FOREIGN KEY (organization_id,wallet_id) REFERENCES wallets (organization_id,id),
  CHECK ((outcome='pending' AND balance_after IS NULL AND job_id IS NULL)
    OR (outcome='approved' AND balance_after IS NOT NULL AND job_id IS NOT NULL)
    OR (outcome='declined' AND balance_after IS NOT NULL AND job_id IS NULL))
);
CREATE TABLE wallet_credits (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  wallet_id bigint NOT NULL REFERENCES wallets,
  amount numeric(12,2) NOT NULL CHECK (amount>0)
);
CREATE TABLE jobs (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  operation_id bigint NOT NULL UNIQUE REFERENCES debit_operations,
  payload jsonb NOT NULL,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','running','done')),
  claim_version bigint NOT NULL DEFAULT 0 CHECK (claim_version>=0),
  worker_id text,
  lease_until timestamptz,
  CHECK ((status='pending' AND worker_id IS NULL AND lease_until IS NULL)
    OR (status IN ('running','done') AND worker_id IS NOT NULL AND lease_until IS NOT NULL))
);
CREATE INDEX ON jobs (id) WHERE status<>'done';
-- Условный внешний сервис. Его запись выполняют отдельной транзакцией.
-- Здесь нет FK, связывающего его COMMIT с обработкой jobs.
CREATE TABLE provider_receipts (
  delivery_key text PRIMARY KEY,
  job_id bigint NOT NULL,
  result text NOT NULL DEFAULT 'accepted'
);
COMMIT;
